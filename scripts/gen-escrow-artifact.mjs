// Copies the compiled LookoutEscrow ABI and creation bytecode into packages/escrow/src/artifact.ts.
//
//   npm run gen -w @lookout/escrow            regenerate after changing contracts/src/LookoutEscrow.sol
//   node scripts/gen-escrow-artifact.mjs --check    fail if the committed file is out of date (used by a test)
//
// The TypeScript client and the contract can never drift apart: the client only ever uses what the compiler produced.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const contracts = fileURLToPath(new URL('../contracts', import.meta.url));
const out = fileURLToPath(new URL('../packages/escrow/src/artifact.ts', import.meta.url));
const inspect = (what) => execFileSync('forge', ['inspect', 'LookoutEscrow', what, ...(what === 'abi' ? ['--json'] : [])], { cwd: contracts, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();

const abi = JSON.parse(inspect('abi'));
const bytecode = inspect('bytecode');
if (!/^0x[0-9a-f]+$/.test(bytecode)) throw new Error('forge did not return bytecode');

const text = `// GENERATED by scripts/gen-escrow-artifact.mjs from contracts/src/LookoutEscrow.sol. Do not edit by hand.
// Regenerate with: npm run gen -w @lookout/escrow

export const escrowAbi = ${JSON.stringify(abi, null, 2)} as const;

export const escrowBytecode = '${bytecode}' as const;
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8').split('\r\n').join('\n'); // git may check the file out with CRLF
  if (current !== text) { console.error('packages/escrow/src/artifact.ts is out of date. Run: npm run gen -w @lookout/escrow'); process.exit(1); }
  console.log('artifact is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${abi.length} abi entries, ${(bytecode.length - 2) / 2} bytes of bytecode)`);
}
